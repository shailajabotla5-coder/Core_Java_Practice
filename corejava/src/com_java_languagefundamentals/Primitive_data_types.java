package com_java_languagefundamentals;

public class Primitive_data_types {

	public static void main(String[] args) {
		
		 int employeeId = 101;
	        byte employeeAge = 22;
	        double employeeSalary = 35000.50;
	        char employeeGrade = 'A';
	        float yearsOfExperience = 2f;
	        boolean employeeIsActive = true;
	        short numberOfLeaves = 5;
	        long employeePhone = 871225902;
	        
             //employee information
	        
	        System.out.println("Employee ID: " + employeeId);
	        System.out.println("Employee Age: " + employeeAge);
	        System.out.println("Employee Salary: " + employeeSalary);
	        System.out.println("Employee Grade: " + employeeGrade);
	        System.out.println("Years of Experience: " + yearsOfExperience);
	        System.out.println("Employee is Active: " + employeeIsActive);
	        System.out.println("Number of Leaves: " + numberOfLeaves);
	        System.out.println("Employee Phone: " + employeePhone);
	}
}
		
		
		
		
		
		
	
